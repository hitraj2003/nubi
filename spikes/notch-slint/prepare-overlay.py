"""Prepare static overlay data and icons from the production sources, offline."""
import json
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter

root = Path(__file__).resolve().parent
source = root.parent.parent / 'ui'
fixtures = json.loads((root / 'fixture.json').read_text(encoding='utf-8'))['overlays']
js = (source / 'overlay.js').read_text(encoding='utf-8')
for name in ['warning', 'info']:
    svg = re.search(r"  " + name + r": '([^']+)'", js)[1]
    svg = svg.replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ', 1).replace('currentColor', '#000')
    (root / f'assets/overlay-{name}.svg').write_text(svg, encoding='utf-8')

def literal(value):
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, list):
        return '[' + ','.join(literal(item) for item in value) + ']'
    if isinstance(value, dict):
        return '{' + ','.join(key + ':' + literal(item) for key, item in value.items()) + '}'
    return json.dumps(value, ensure_ascii=False)

lines = ['// Generated by prepare-overlay.py from fixture.json.',
         'export struct OverlayOption { label: string, description: string, selected: bool }',
         'export struct OverlayQuestion { header: string, question: string, multi: bool, options: [OverlayOption] }',
         'export struct OverlayRequest { title: string, meta: string, provider: string, summary: string, parameters: string, seconds: int }',
         'export global OverlayFixture {']
for name, request in fixtures.items():
    values = json.loads(request['tool_input'])
    summary = next((values[key] for key in ['command', 'file_path', 'path', 'url', 'pattern'] if values.get(key)), next(iter(values.values()), ''))
    row = dict(title='Question' if request['kind']=='question' else f"Allow {request.get('tool_name', 'tool')}?",
               meta=f"{request['provider'].title()} · {request['name']}", provider=request['provider'],
               summary=' '.join(str(summary).split()), parameters=request['tool_input'],
               seconds=(request['expires_ms']-request['created_ms'])//1000)
    lines.append(f'    out property <OverlayRequest> {name}: {literal(row)};')
questions = [dict(header=q.get('header',''),question=q['question'],multi=q.get('multiSelect',False),
                  options=[dict(label=o['label'],description=o.get('description',''),selected=False) for o in q['options']])
             for q in fixtures['question']['questions']]
lines.extend(['    out property <[OverlayQuestion]> questions: '+literal(questions)+';', '}'])
(root / 'ui/overlay-fixture.slint').write_text('\n'.join(lines)+'\n', encoding='utf-8')

# The overlay has different shadows and radius from the panel. Use its actual CSS.
scale, padding, size = 3, 80, 65
extent = (size + 2*padding)*scale
for dark in [False, True]:
    result = Image.new('RGBA', (extent, extent))
    for dy, blur, spread, alpha in [(20,50,-12,.5 if dark else .16),(8,20,-4,.4 if dark else .12),(2,8,-2,.6 if dark else .18)]:
        mask = Image.new('L', (extent, extent))
        ImageDraw.Draw(mask).rounded_rectangle(((padding-spread)*scale,(padding+dy-spread)*scale,
            (padding+size+spread)*scale-1,(padding+size+dy+spread)*scale-1),radius=(24+spread)*scale,fill=round(alpha*255))
        mask = mask.filter(ImageFilter.GaussianBlur(blur*scale/2))
        layer = Image.new('RGBA', (extent,extent)); layer.putalpha(mask)
        result = Image.alpha_composite(result, layer)
    result.save(root / f"assets/overlay-shadow-{'dark' if dark else 'light'}.png")
print('Prepared overlay fixtures, source icons, and overlay shadows.')
